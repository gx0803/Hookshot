#!/usr/bin/env python3
"""Generate gpu/vk/menu_i18n.h from the checked-in Chinese translation table.

The menu's display strings stay in English in the source (they are also the ini keys and are
compared with strcmp in a few places). At draw time tr() looks an English string up in the table
below and returns the Chinese one when the menu language is Chinese, else the original pointer.
Keeping the table in a JSON file next to the header makes translations reviewable and增量 additions
possible without touching the menu's logic.

    python -I -B scripts/gen_menu_i18n.py            # write gpu/vk/menu_i18n.h
    python -I -B scripts/gen_menu_i18n.py --check    # compare instead of writing (CI)

The header is self-contained C: a sorted static array and a linear lookup (the menu draws a few
dozen strings a frame; a map would not be worth it). Only ASCII bytes are emitted; the Chinese is
spelled as \\uXXXX escapes so the file is portable across the Windows and Linux compilers.
"""
import argparse
import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
DATA = ROOT / "gpu" / "vk" / "menu_zh.json"
OUT = ROOT / "gpu" / "vk" / "menu_i18n.h"


def c_escape(s: str) -> str:
    """ASCII-only C string body: printable ASCII as-is, everything else as \\uXXXX (surrogates paired)."""
    out = []
    for ch in s:
        o = ord(ch)
        if ch == '"':
            out.append('\\"')
        elif ch == "\\":
            out.append("\\\\")
        elif 0x20 <= o <= 0x7E:
            out.append(ch)
        elif o <= 0xFFFF:
            out.append("\\u%04x" % o)
        else:
            o -= 0x10000
            out.append("\\u%04x\\u%04x" % (0xD800 + (o >> 10), 0xDC00 + (o & 0x3FF)))
    return "".join(out)


def render(pairs) -> str:
    lines = [
        "// Generated by scripts/gen_menu_i18n.py from gpu/vk/menu_zh.json -- do not edit by hand.",
        "// The English key doubles as the ini key / strcmp subject; only the drawn text is translated.",
        "#pragma once",
        "#include <string.h>",
        "",
        "namespace mkwvk::menu_i18n {",
        "",
        "// (0) English, the source default; (1) 简体中文, the only translation shipped for now.",
        "inline int language = 0;",
        "",
        "struct Entry { const char* en; const char* zh; };",
        "// Sorted by en; generated from the checked-in table. Keep the source strings verbatim.",
        "static const Entry kTable[] = {",
    ]
    for en, zh in pairs:
        lines.append('    {"%s", "%s"},' % (c_escape(en), c_escape(zh)))
    lines += [
        "};",
        "static const int kTableLen = (int)(sizeof kTable / sizeof kTable[0]);",
        "",
        "/// Translate a drawn string. Returns the original pointer when English or not in the table,",
        "/// so callers never allocate and no string's lifetime changes.",
        "inline const char* tr(const char* en) {",
        "    if (!language || !en || !*en) return en;   // (English: zero overhead beyond a branch)",
        "    int lo = 0, hi = kTableLen - 1;",
        "    while (lo <= hi) {",
        "        int mid = (lo + hi) / 2;",
        "        int cmp = strcmp(en, kTable[mid].en);",
        "        if (cmp < 0) hi = mid - 1;",
        "        else if (cmp > 0) lo = mid + 1;",
        "        else return kTable[mid].zh;",
        "    }",
        "    return en;   // (untranslated: keep the English rather than draw nothing)",
        "}",
        "",
        "} // namespace mkwvk::menu_i18n",
        "",
    ]
    return "\n".join(lines)


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--check", action="store_true")
    a = ap.parse_args()
    data = json.loads(DATA.read_text(encoding="utf-8"))
    pairs = sorted(((x["en"], x["zh"]) for x in data["entries"]), key=lambda p: p[0])
    text = render(pairs)
    if a.check:
        if not OUT.is_file() or OUT.read_text(encoding="utf-8") != text:
            print("menu_i18n.h is out of date (or missing); run scripts/gen_menu_i18n.py")
            return 1
        print("menu_i18n.h up to date (%d entries)" % len(pairs))
        return 0
    OUT.write_text(text, encoding="utf-8", newline="\n")
    print("wrote %s (%d entries, %d B)" % (OUT, len(pairs), len(text.encode("utf-8"))))
    return 0


if __name__ == "__main__":
    sys.exit(main())
